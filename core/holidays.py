# 第 147 步：由数据派生，手写会漏（评价10 抓到漏了 2025）
SUPPORTED_YEARS: tuple[int, ...] = tuple(sorted(ARRANGEMENTS))


def _parse(text: str) -> date:
    return date.fromisoformat(text)


def _expand() -> tuple[dict[date, str], set[date]]:
    """把区间展开成：放假日期 → 节日名，以及补班日期集合。"""
    off: dict[date, str] = {}
    work: set[date] = set()
    for entries in ARRANGEMENTS.values():
        for name, start, end, workdays in entries:
            cursor = _parse(start)
            last = _parse(end)
            while cursor <= last:
                # 同一天被两条安排重复覆盖是不该发生的；真发生了以后者为准，
                # 但这里宁可留个显式异常，免得数据写错却静默通过。
                if cursor in off:
                    raise ValueError(f"{cursor} 被两条放假安排重复覆盖：{off[cursor]} / {name}")
                off[cursor] = name
                cursor += timedelta(days=1)
            for day in workdays:
                parsed = _parse(day)
                if parsed in work:
                    raise ValueError(f"{parsed} 被重复标为补班日")
                work.add(parsed)
    overlap = set(off) & work
    if overlap:
        raise ValueError(f"同一天既放假又补班：{sorted(overlap)}")
    return off, work


#: 放假日期 → 节日名（用于"休"标记与悬停提示）。
OFF_DAYS, WORK_DAYS = _expand()


def has_data(year: int) -> bool:
    """这一年有没有官方安排数据（决定要不要显示休 / 班）。"""
    return year in ARRANGEMENTS


def status_of(day: date) -> str:
    """这一天是放假（"off"）、调休上班（"work"）还是普通日子（""）。"""
    if day in OFF_DAYS:
        return REST
    if day in WORK_DAYS:
        return WORK
    return ""


def label_of(status: str) -> str:
    """状态 → 格子里那个小字（前端直接用，不硬编码中文）。"""
    return {REST: "休", WORK: "班"}.get(status, "")


def holiday_name(day: date) -> str:
    """这一天若是法定假期，返回节日名（例如"国庆节"）；否则空串。"""
    return OFF_DAYS.get(day, "")


def covered_years() -> Iterable[int]:
    return sorted(ARRANGEMENTS)
